"""Preserve the eighteen unattempted slots without running or tuning on them."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PREVIOUS = ROOT.parent / "scoped-request-coverage-development-2026-11-17"


def read(path):
    return json.loads(Path(path).read_bytes())


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    contract = read(PREVIOUS / "qualification-contract.json")
    prior = read(PREVIOUS / "qualification-batch-summary.json")
    retained = prior["unattempted_ids"]
    assert len(retained) == 18 and not {"cq1-a27", "cq1-a28"}.intersection(retained)
    paths = {}
    cases = {}
    for cid in retained:
        case = contract["cases"][cid]
        assert not (PREVIOUS / "actual-cq1" / f"{cid}.started.json").exists()
        assert digest(case["corpus_path"]) == case["plan"]["corpus_sha256"]
        assert digest(case["requested_scopes"]) == case["requested_scopes_sha256"]
        cases[cid] = hashlib.sha256(json.dumps(case, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
        for path in (case["corpus_path"], case["requested_scopes"]):
            paths[path] = digest(path)
    for name in ("source_reference_path", "requested_scope_manifest_path"):
        path = contract[name]
        assert digest(path) == contract["input_sha256"][path]
        paths[path] = digest(path)
    value = {"prior_contract_sha256": contract["contract_sha256"], "retained_count": 18,
        "retained_case_ids": retained, "case_envelope_sha256": cases, "retained_input_sha256": paths,
        "excluded_consumed_ids": ["cq1-a27", "cq1-a28"],
        "next_pool_requirements": "Freeze two fresh answerable replacements before any new twenty-case execution. "
            "Retain these eighteen questions, source corpora, branch plans and scopes exactly. "
            "No replacement fact has been selected or generated by this preservation check.",
        "thresholds": {"answerable": "9/10", "partial": "2/2", "missing": "4/4", "conflict": "2/2",
                       "injection": "2/2", "critical_errors": 0},
        "actual_model_calls": 0, "qualification_authorized": False}
    with (ROOT / "qualification-roster-preservation.json").open("x", encoding="utf-8") as handle:
        json.dump(value, handle, indent=2)
        handle.write("\n")
    print(json.dumps({"retained_unattempted": 18, "fresh_replacement_slots_pending": 2}))


if __name__ == "__main__":
    main()
